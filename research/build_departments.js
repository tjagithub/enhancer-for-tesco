// Compacts Tesco's All Departments response into content/departments.js (names only; links are built from slugs).
// Usage: node research/build_departments.js [research/fixtures/categories.json]
const fs = require('fs');
const path = require('path');

const SRC = process.argv[2] || path.join(__dirname, 'fixtures', 'categories.json');
const OUT = path.join(__dirname, '..', 'content', 'departments.js');

// [name, children] for branches, plain name for leaf aisles.
const compact = (node) => (node.children && node.children.length ? [node.name, node.children.map(compact)] : node.name);
const taxonomy = JSON.parse(fs.readFileSync(SRC, 'utf8'))[0].data.taxonomy;
const tree = taxonomy.map(compact);
const body = '// Generated by research/build_departments.js from Tesco\'s menu data. Do not edit.\n' +
  'globalThis.THL_DEPARTMENTS = ' + JSON.stringify(tree) + ';\n';
fs.writeFileSync(OUT, body);
console.log('wrote', path.relative(process.cwd(), OUT), (body.length / 1024).toFixed(1) + ' KB,', tree.length, 'departments');
